"""Plan and run backend conversion to RPoem by delegating to the sibling converters.

Python -> 2Poem, Java -> Java_to, COBOL -> COBOL_to (all with target rpoem).
PHP (Laravel) and Perl (Mojolicious/Dancer) are converted in-process by php.py / perl.py (literal returns only, the rest 501).
Everything else (Node.js/Nest/Express, and every frontend) cannot be converted yet:
it is never dropped silently, it is written to MIGRATION.md as a TODO with the reason.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from dataclasses import dataclass

from .detect import Finding, scan

_SIBLING_BINS = {
    "java_to": ("Java_to", "java_to"),
    "cobol_to": ("COBOL_to", "cobol_to"),
}


@dataclass
class Step:
    framework: str
    tool: str          # "2poem" | "java_to" | "cobol_to" | "todo"
    argv: list         # empty for todo
    out: str
    note: str = ""


def _exe(name: str):
    env = os.environ.get("TORPOREA_" + name.upper())
    if env and os.path.exists(env):
        return env
    found = shutil.which(name)
    if found:
        return found
    repo, binname = _SIBLING_BINS[name]
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
    for ext in ("", ".exe"):
        p = os.path.join(root, repo, "target", "release", binname + ext)
        if os.path.exists(p):
            return p
    return None


def plan(src: str, out: str, rpoem_path: str = "../RPoem") -> list:
    steps = []
    done = set()
    for f in scan(src):
        if f.kind == "frontend":
            steps.append(Step(f.framework, "todo", [], "", "frontend (%s): only static JSX is ported to Reaxt pages; state, effects and data fetching are not ported" % f.framework))
            continue
        if f.language == "python" and "python" not in done:
            done.add("python")
            o = os.path.join(out, "backend-python")
            steps.append(Step(f.framework, "2poem", [sys.executable, "-m", "topoem", "convert", src, "-o", o, "--target", "rpoem", "--rpoem-path", rpoem_path], o))
        elif f.language == "java" and "java" not in done:
            done.add("java")
            o = os.path.join(out, "backend-java")
            exe = _exe("java_to")
            steps.append(Step(f.framework, "java_to", [exe or "java_to", "convert", src, "--target", "rpoem", "--out", o, "--rpoem-path", rpoem_path], o,
                              "" if exe else "java_to binary not found (set TORPOREA_JAVA_TO)"))
        elif f.language == "cobol" and "cobol" not in done:
            done.add("cobol")
            o = os.path.join(out, "backend-cobol")
            exe = _exe("cobol_to")
            steps.append(Step(f.framework, "cobol_to", [exe or "cobol_to", "--src", src, "--target", "rpoem", "--out", o], o,
                              "" if exe else "cobol_to binary not found (set TORPOREA_COBOL_TO)"))
        elif f.language == "php" and "php" not in done:
            done.add("php")
            o = os.path.join(out, "backend-php")
            steps.append(Step(f.framework, "php", [], o, "Laravel routes; only single literal returns are translated, the rest answer 501"))
        elif f.language == "perl" and "perl" not in done:
            done.add("perl")
            o = os.path.join(out, "backend-perl")
            steps.append(Step(f.framework, "perl", [], o, "Mojolicious/Dancer routes; only single literal responses are translated, the rest answer 501"))
        elif f.language in ("python", "java", "cobol", "php", "perl"):
            continue
        else:
            steps.append(Step(f.framework, "todo", [], "", "backend (%s/%s) -> RPoem conversion is not implemented yet" % (f.framework, f.language)))
    return steps


def write_migration(out: str, steps: list, results: dict) -> str:
    os.makedirs(out, exist_ok=True)
    lines = ["# MIGRATION.md", "", "Generated by 2rporea. Business logic is NOT claimed to be ported automatically; review every item.", ""]
    inv = results.get("_inventory") or {}
    for s in steps:
        if s.tool == "todo":
            lines.append("- TODO `%s`: %s" % (s.framework, s.note))
        else:
            r = results.get(s.framework)
            status = "ok" if r == 0 else "FAILED (exit %s)" % r if r is not None else "not run"
            lines.append("- `%s` via `%s`: %s -> `%s`%s" % (s.framework, s.tool, status, s.out, (" (" + s.note + ")") if s.note else ""))
    if inv.get("routes") or inv.get("pages") or inv.get("components"):
        lines += ["", "## Reaxt porting inventory (not converted; what the port must cover)", ""]
        lines += ["- route `%s %s` (%s, %s)" % (m, path, fw, f) for fw, m, path, f in inv.get("routes", [])]
        lines += ["- page `%s` <- %s" % (r, f) for r, f in inv.get("pages", [])]
        lines += ["- component %s" % c for c in inv.get("components", [])]
    p = os.path.join(out, "MIGRATION.md")
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return p


def run(src: str, out: str, rpoem_path: str = "../RPoem", dry_run: bool = False, node: bool = False) -> int:
    steps = plan(src, out, rpoem_path)
    from .inventory import inventory
    results = {"_inventory": inventory(src)}
    if not dry_run:
        for s in steps:
            if s.tool in ("php", "perl"):
                if s.tool == "php":
                    from .php import write as lang_write
                else:
                    from .perl import write as lang_write
                r = lang_write(src, s.out, rpoem_path)
                s.note = "%(routes)d routes, %(translated)d translated, %(todo)d TODO (501), PATCH routes: %(patch)d" % r
                results[s.framework] = 0
                continue
            if s.tool == "todo" or s.note.endswith(")") and "not found" in s.note:
                continue
            results[s.framework] = subprocess.call(s.argv)
    inv = results["_inventory"]
    if (inv["routes"] or inv["pages"]) and not dry_run:
        from .reaxt_gen import write as reaxt_write
        reaxt_write(os.path.join(out, "reaxt-server"), inv["routes"], pages=inv["pages"], src_root=src)
    if node and inv["routes"] and not dry_run:
        from .node_opt import write as node_write
        node_write(out, inv["routes"])
    write_migration(out, steps, results)
    for s in steps:
        print("%-8s %-9s %s" % (s.framework, s.tool, s.note or s.out))
    bad = [k for k, v in results.items() if not k.startswith("_") and v != 0]
    return 1 if bad or not steps else 0
