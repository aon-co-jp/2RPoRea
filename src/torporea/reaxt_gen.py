"""Emit a Reaxt (Rust) server scaffold from the route inventory.

Every route becomes a Connect action whose handler returns HTTP 501 with a TODO naming the
original route and file. Business logic is NOT ported; this only fixes the shape of the Reaxt app.
GET routes get a `Get` prefix so Reaxt exposes them as queries.
"""
from __future__ import annotations

import os
import re


def _method_name(m: str, path: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", path.replace(":", " By "))
    body = "".join(w[:1].upper() + w[1:] for w in words) or "Root"
    prefix = {"GET": "Get", "POST": "", "PUT": "Put", "PATCH": "Patch", "DELETE": "Delete"}.get(m, "")
    return prefix + body


def page_file(route: str) -> str:
    """Reaxt `pages/` convention file name for a route: /blog/:slug -> blog/[slug].rs."""
    r = route.strip("/")
    if not r:
        return "index.rs"
    parts = []
    for seg in r.split("/"):
        if seg.startswith(":"):
            seg = "[" + seg[1:] + "]"
        elif seg.startswith("*"):
            seg = "[..." + seg[1:] + "]"
        parts.append(seg)
    return "/".join(parts) + ".rs"


def _component_text(src_root: str, ref: str):
    """Source of a page file, or of the file defining component `Name` for a `file#Name` reference."""
    rel, _, comp = ref.partition("#")
    if not comp:
        try:
            return open(os.path.join(src_root, rel), encoding="utf-8", errors="replace").read()
        except OSError:
            return None
    pat = re.compile(r"(?:function\s+%s\b|(?:const|let|var)\s+%s\s*=)" % (comp, comp))
    for d, dirs, files in os.walk(src_root):
        dirs[:] = [x for x in dirs if x not in ("node_modules", ".git", "target", "dist", "build")]
        for fn in files:
            if fn.endswith((".jsx", ".tsx", ".js", ".ts")):
                try:
                    tx = open(os.path.join(d, fn), encoding="utf-8", errors="replace").read()
                except OSError:
                    continue
                if pat.search(tx):
                    return tx
    return None


def render(routes: list, name: str = "ported-app", pages: list = (), src_root: str = "") -> str:
    seen, consts, regs = set(), [], []
    for fw, m, path, f in routes:
        mn = _method_name(m, path)
        i = 2
        base = mn
        while mn in seen:
            mn = f"{base}{i}"; i += 1
        seen.add(mn)
        c = re.sub(r"(?<!^)(?=[A-Z])", "_", mn).upper()
        consts.append(f'    const {c}: reaxt_actions::Action<(), String> = reaxt_actions::Action::new("app.v1.Routes", "{mn}");')
        msg = f"TODO: port {m} {path} from {f} ({fw})".replace('"', "'")
        regs.append(f'                .action(&{c}, |_, _: ()| Err(reaxt::backend::Denied::new(501, "{msg}")))')
    pg = []
    for route, f in pages:
        msg = f"TODO: port page {route} from {f}".replace('"', "'")
        body = None
        if src_root:
            from .jsx import convert_file, unported
            text = _component_text(src_root, f)
            if text is not None:
                body = convert_file(text, resolve=lambda c: _component_text(src_root, "#" + c))
                notes = unported(text)
                if notes:
                    msg += " | not ported: " + "; ".join(notes).replace('"', "'")
        if body:
            pg.append(f'        .page("{page_file(route)}", reaxt::RenderMode::SsrHydrate, |_| reaxt::react::VNode::element("main").attr("data-todo", "{msg}").child({body}).build())')
            continue
        pg.append(f'        .page("{page_file(route)}", reaxt::RenderMode::SsrHydrate, |_| reaxt::react::VNode::element("main").child(reaxt::react::VNode::text("{msg}")).build())')
    return ('//! Generated by 2rporea. Every handler is a 501 stub: the business logic is NOT ported.\n'
            'fn main() {\n    use reaxt::app::App;\n    use reaxt_actions::ModuleActions;\n    use std::sync::Arc;\n\n'
            + "\n".join(consts) + '\n    let port = std::env::args().nth(1).unwrap_or_else(|| "8080".into());\n'
            f'    let app = App::new("{name}")\n        .global_guard(reaxt_actions::csrf_guard)\n'
            '        .module(\n            reaxt::backend::Module::new()\n' + "\n".join(regs) + '\n        )\n' + ("\n".join(pg) + "\n" if pg else "") + '        .finish();\n'
            '    let l = std::net::TcpListener::bind(format!("127.0.0.1:{port}")).expect("bind");\n'
            '    reaxt::server::serve(Arc::new(app), l);\n}\n')


def write(out: str, routes: list, reaxt_path: str = "../Reaxt", name: str = "ported-app", pages: list = (), src_root: str = "") -> str:
    os.makedirs(os.path.join(out, "src"), exist_ok=True)
    with open(os.path.join(out, "Cargo.toml"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(f'[package]\nname = "{name}"\nversion = "0.0.1"\nedition = "2021"\npublish = false\n\n[dependencies]\n'
                 f'reaxt = {{ path = "{reaxt_path}" }}\nreaxt-actions = {{ path = "{reaxt_path}/reaxt-actions" }}\n')
    p = os.path.join(out, "src", "main.rs")
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(routes, name, pages, src_root))
    return p
